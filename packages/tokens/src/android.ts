// Android resources for the home-screen widget (P9): values/colors.xml (light) and
// values-night/colors.xml (dark), read by Glance `ColorProviders(day, night)`.
import { parseHex } from './contrast.js';
import { COLORS, type Theme } from './tokens.js';

const byte = (n: number) => n.toString(16).padStart(2, '0').toUpperCase();

/** `#RRGGBB` or `rgba(r,g,b,a)` → Android `#AARRGGBB`. */
export function toAndroidColor(value: string): string {
  const rgba = /^rgba\((\d+),(\d+),(\d+),([\d.]+)\)$/.exec(value.replaceAll(' ', ''));
  const [r, g, b, a] = rgba
    ? (rgba.slice(1).map(Number) as [number, number, number, number])
    : [...parseHex(value), 1];
  return `#${byte(Math.round(a * 255))}${byte(r)}${byte(g)}${byte(b)}`;
}

/** Resource names are `dgd_<token>` with underscores (`--color-text-muted` → `dgd_text_muted`). */
export function toColorsXml(theme: Theme): string {
  const colors = Object.entries(COLORS).map(
    ([name, v]) =>
      `    <color name="dgd_${name.replaceAll('-', '_')}">${toAndroidColor(v[theme])}</color>`,
  );
  return [
    '<?xml version="1.0" encoding="utf-8"?>',
    '<!-- Generated by @dgd/tokens (docs/design/COLOR_TOKENS.md). Do not edit. -->',
    '<resources>',
    ...colors,
    '</resources>',
    '',
  ].join('\n');
}
