// tokens.css: a Tailwind 4 theme whose utilities (`bg-primary`, `text-h1`, `shadow-md`…) resolve to
// CSS variables, so themes switch by overriding variables alone.
import {
  COLORS,
  MOTION,
  RADII,
  SHADOWS,
  type Theme,
  TYPE_SCALE,
  type TypeStyle,
} from './tokens.js';

const indent = (text: string) =>
  text
    .split('\n')
    .map((l) => `  ${l}`)
    .join('\n');
const block = (selector: string, lines: string[]) =>
  `${selector} {\n${indent(lines.join('\n'))}\n}`;
const media = (query: string, selector: string, lines: string[]) =>
  `@media ${query} {\n${indent(block(selector, lines))}\n}`;

const themeVars = (theme: Theme) => [
  ...Object.entries(COLORS).map(([name, v]) => `--color-${name}: ${v[theme]};`),
  ...Object.entries(SHADOWS).map(([name, v]) => `--shadow-${name}: ${v[theme]};`),
];

export function toCss(): string {
  const type = Object.entries(TYPE_SCALE) as [string, TypeStyle][];
  const dark = themeVars('dark');
  return `${[
    '/* Generated by @dgd/tokens from src/tokens.ts (docs/design/COLOR_TOKENS.md). Do not edit. */',
    block('@theme', [
      // Only tokens exist: the default palette, shadows and text sizes are removed (no raw colours).
      '--color-*: initial;',
      '--shadow-*: initial;',
      '--text-*: initial;',
      ...themeVars('light'),
      ...Object.entries(RADII).map(([name, v]) => `--radius-${name}: ${v};`),
      ...type.flatMap(([name, t]) => [
        `--text-${name}: ${t.size};`,
        `--text-${name}--line-height: ${t.lineHeight};`,
        `--text-${name}--font-weight: ${t.weight};`,
      ]),
      `--ease-standard: ${MOTION.ease};`,
    ]),
    block(':root', [
      'color-scheme: light dark;',
      ...Object.entries(MOTION.duration).map(([name, v]) => `--duration-${name}: ${v};`),
    ]),
    // An explicit choice (data-theme on <html>) wins; otherwise follow the system (COLOR_TOKENS §6).
    block(":root[data-theme='light']", ['color-scheme: light;']),
    block(":root[data-theme='dark']", ['color-scheme: dark;', ...dark]),
    media('(prefers-color-scheme: dark)', ":root:not([data-theme='light'])", dark),
    // Focus is always visible: 2px ring + 2px offset in the info hue, distinct from primary.
    `@layer base {
${indent(block(':focus-visible', ['outline: 2px solid var(--color-focus-ring);', 'outline-offset: 2px;']))}
}`,
    // Bengali: taller lines and a 13px minimum (TYPOGRAPHY §3). Only where `lang` is set: custom
    // properties inherit, so matching every element would only add style work.
    block(
      ":root:lang(bn), [lang|='bn']",
      type.flatMap(([name, t]) => [
        ...(t.lineHeightBn ? [`--text-${name}--line-height: ${t.lineHeightBn};`] : []),
        ...(t.sizeBn ? [`--text-${name}: ${t.sizeBn};`] : []),
      ]),
    ),
    media(
      '(width < 40rem)',
      ':root',
      type.flatMap(([name, t]) => (t.sizeMobile ? [`--text-${name}: ${t.sizeMobile};`] : [])),
    ),
  ].join('\n\n')}\n`;
}
